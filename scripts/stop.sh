#!/bin/bash
# =============================================================================
# stop.sh — остановка контейнера
#
# Использование:
#   bash scripts/stop.sh        # остановить (данные сохраняются)
#   bash scripts/stop.sh --rm   # остановить и удалить контейнер + образ
# =============================================================================

set -euo pipefail

PROJECT_DIR="/opt/hydromet_bulletin"
cd "$PROJECT_DIR"

MODE="${1:-}"

echo "============================================="
echo "  Hydromet Bulletin — остановка"
echo "============================================="

if [[ "$MODE" == "--rm" ]]; then
    echo "Остановка и удаление контейнера и образа..."
    docker compose down --rmi local --remove-orphans
    echo "  Контейнер и образ удалены."
    echo "  Данные в output/ и logs/ сохранены."
else
    echo "Остановка контейнера..."
    docker compose stop
    echo "  Контейнер остановлен. Данные сохранены."
    echo "  Для повторного запуска: bash scripts/deploy.sh"
fi

echo "============================================="
