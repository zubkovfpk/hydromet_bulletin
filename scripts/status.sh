#!/bin/bash
# =============================================================================
# status.sh — статус контейнера, последние бюллетени, последние строки лога
# =============================================================================

PROJECT_DIR="/opt/hydromet_bulletin"
cd "$PROJECT_DIR"

echo "============================================="
echo "  Hydromet Bulletin — статус"
echo "============================================="

# ── Docker ────────────────────────────────────────────────────────────────
echo ""
echo "[ Контейнер ]"
docker compose ps 2>/dev/null || echo "  Docker Compose недоступен"

# ── Последние файлы в output/ ─────────────────────────────────────────────
echo ""
echo "[ Последние бюллетени ]"
if ls output/*.docx 2>/dev/null | head -5; then
    ls -lth output/*.docx 2>/dev/null | head -5 | awk '{print "  " $6, $7, $8, $9}'
else
    echo "  Файлов ещё нет"
fi

# ── Последние строки лога ─────────────────────────────────────────────────
echo ""
echo "[ Последние 10 строк hydromet.log ]"
if [ -f logs/hydromet.log ]; then
    tail -10 logs/hydromet.log | sed 's/^/  /'
else
    echo "  Лог-файл отсутствует"
fi

# ── Ближайший запуск по расписанию ───────────────────────────────────────
echo ""
echo "[ Расписание ]"
echo "  09:00 MSK (06:00 UTC) — утренний бюллетень"
echo "  19:00 MSK (16:00 UTC) — вечерний бюллетень"
echo ""
echo "  Текущее время UTC: $(date -u '+%Y-%m-%d %H:%M:%S')"
echo "  Текущее время MSK: $(TZ='Europe/Moscow' date '+%Y-%m-%d %H:%M:%S')"

echo "============================================="
